#!/usr/bin/env python3
"""m2_optables.py - writes tools/m2host/huc6280_optab.h: each HuC6280 opcode's size and the classes the cycle model
(docs/11) and the timing check (docs/13) need, from huc6280.py's table. A description of the CPU, not of the game.

    huc_size[op]   bytes, opcode included
    huc_class[op]  OC_DEC: ADC / SBC (+1 with D)   OC_T: AND / ORA / EOR / ADC (+3 after SET)
                   OC_BCC: Bcc on a flag (cond in huc_cond[op])   OC_BBX: BBR / BBS   OC_BRA: BRA / BSR (always taken)
                   OC_BLK: a block move (+6 a byte; length at +5)   OC_SET: SET   OC_IGATE: CLI / SEI / PLP
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from huc6280 import OPS, size                             # noqa: E402

CLS = dict(DEC=1, T=2, BCC=4, BBX=8, BRA=16, BLK=32, SET=64, IGATE=128)
COND = {'BPL': 1, 'BMI': 2, 'BVC': 3, 'BVS': 4, 'BCC': 5, 'BCS': 6, 'BNE': 7, 'BEQ': 8}


def main():
    sz, cl, cd = [], [], []
    for op in range(256):
        m, mode = OPS[op] if OPS[op] else ('???', 'imp')
        c = 0
        if m in ('ADC', 'SBC'): c |= CLS['DEC']
        if m in ('AND', 'ORA', 'EOR', 'ADC'): c |= CLS['T']
        if m in COND: c |= CLS['BCC']
        if mode == 'zrel': c |= CLS['BBX']
        if m in ('BRA', 'BSR'): c |= CLS['BRA']
        if mode == 'blk': c |= CLS['BLK']
        if m == 'SET': c |= CLS['SET']
        if m in ('CLI', 'SEI', 'PLP'): c |= CLS['IGATE']
        sz.append(size(op)); cl.append(c); cd.append(COND.get(m, 0))

    def table(name, v):
        rows = [', '.join('%3d' % x for x in v[i:i + 16]) for i in range(0, 256, 16)]
        return 'static const unsigned char %s[256] = {\n    %s\n};\n' % (name, ',\n    '.join(rows))
    out = ['/* huc6280_optab.h - generated by tools/m2_optables.py from tools/huc6280.py: opcode sizes and classes */',
           '#pragma once'] + ['#define OC_%s %d' % kv for kv in CLS.items()] + \
          ['/* huc_cond: 1 BPL, 2 BMI, 3 BVC, 4 BVS, 5 BCC, 6 BCS, 7 BNE, 8 BEQ */',
           table('huc_size', sz), table('huc_class', cl), table('huc_cond', cd)]
    p = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'm2host', 'huc6280_optab.h')
    open(p, 'w').write('\n'.join(out))
    print('wrote', p)


if __name__ == '__main__':
    main()
