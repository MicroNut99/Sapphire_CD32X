#!/usr/bin/env python3
"""m3_combo.py <gen dir> <pagemap file> <out dir> - docs/39: the translated blocks of the whole game in combinations.

One build can't hold every block (46 of them, 5.9 MB on the SH2) in the cart's 2 MB window 1, but the game never has
more than ~14 of them in its RAM at once (tools/m3_pagemap.py). So window 1 holds:
    0x200000  the current combination's file: a header, its blocks, their table (blocks_cb) - up to 640 KB, loaded
              from the CD (file 104 + i, C<ii>.BIN) when the game's overlays change
    0x2A0000  the shared blocks (the System Card's, the kernel's, base RAM's) and their table (blocks_sh): IMAGE21.RAW,
              file 21 (cart slot 21), loaded once
Each combination is its own build (<out>/c<ii>/, a GEN dir for saspeed's Makefile, COMBO=1): the same runtime, the same
shared part (both are checked equal across the builds), its own LEVEL00.BIN. The directory (combo_dir.c, in every
build's ROM the same) says, for each block of a combination, its bank, its combination, a few sample bytes and the hash
of its code bytes (the mask's), so the runtime finds which file to load from the code the game has put in a bank.

The combinations: the pagemap's sets of blocks seen at once, less the shared ones, the subsets dropped, then merged in
time order while they fit (COMBO_MAX, 0x9F000 with the tables). Sizes from SIZES (sh-elf-size of each block, + 16 KB).
"""
import os
import re
import shutil
import sys

import numpy as np

SHARED = ['00_0', '01_0', '02_0', '68_0', '69_1', '6A_1', '6B_1', '6C_0', '74_0', '87_0', 'F8_0']
COMBO_MAX = int(os.environ.get('COMBO_MAX', '0x9F000'), 0)
# COMBO_SPLIT=<work>:<window dir>,<window dir>,... : each combination split (m3_speedtest.py split, SPLIT_ASM / SPLIT_MIN
# from the environment) with the hot instructions of all those windows; its hot code (hot_stage.s, hot.c) goes in its
# file and is copied to SDRAM when it is loaded (saspeed_combo.blk .hot)
W, SPLIT_DIRS = (os.environ['COMBO_SPLIT'].split(':', 1)[0], os.environ['COMBO_SPLIT'].split(':', 1)[1].split(',')) \
    if os.environ.get('COMBO_SPLIT') else (None, None)
# COMBO_OWN=<i>:<window>[+<window>];... : the windows that run combination i (their counts decide its overlay banks' hot
# code, SPLIT_MIN_FOR); without one, all of them
OWN = {int(a): b for a, b in (x.split(':') for x in os.environ.get('COMBO_OWN', '').split(';') if x)}
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import m3_speedtest as sp                                   # noqa: E402


def fnv(b):
    f = 2166136261
    for x in b.tolist():
        f = ((f ^ x) * 16777619) & 0xFFFFFFFF
    return f


def main():
    gen, pm, out = sys.argv[1:4]
    sizes = dict((l.split()[0], int(l.split()[1])) for l in open(os.environ.get('SIZES', '/tmp/shsz/sizes.txt')))
    seq = []
    for l in open(pm):
        if l.startswith('stage'): continue
        s = frozenset(l.split()[2:]) - set(SHARED)
        if s and (not seq or seq[-1] != s): seq.append(s)
    sets = []                                               # (maximal sets, in the order they first come)
    for s in seq:
        if any(s <= t for t in seq if t != s and len(t) > len(s)): continue
        if s not in sets: sets.append(s)
    combos = []
    for s in sets:
        if combos and sum(sizes[k] for k in combos[-1] | s) <= COMBO_MAX: combos[-1] = combos[-1] | s
        else: combos.append(set(s))
    src = open(os.path.join(gen, 'blocks.c')).read()
    arr = {}
    for m in re.finditer(r'static const uint8_t (code|mask)_([0-9A-F]{2}_\d+)\[8192\] = \{([^}]*)\}', src):
        arr[(m.group(1), m.group(2))] = np.array([int(x) for x in m.group(3).split(',')], np.uint8)
    head = src[:src.index('void blk_')]
    # the directory: each combination's blocks (a block in two combinations: the first)
    owner = {}
    for i, c in enumerate(combos):
        for k in sorted(c): owner.setdefault(k, i)
    d = ['/* combo_dir.c - generated by tools/m3_combo.py (docs/39): which combination file holds a block, by its code */',
         '#include <stdint.h>',
         'typedef struct { uint8_t bank, combo; uint16_t pos[8]; uint8_t val[8]; uint32_t hash; const uint8_t *bits; } ComboDir;']
    ents = []
    for k in sorted(owner):
        code, mask = arr[('code', k)], arr[('mask', k)].astype(bool)
        where = np.nonzero(mask)[0]
        pick = where[np.linspace(0, len(where) - 1, 8).astype(int)]
        bits = np.packbits(mask, bitorder='little')
        d.append('static const uint8_t bits_%s[1024] = {%s};' % (k, ','.join(str(x) for x in bits.tolist())))
        ents.append('    { 0x%s, %d, {%s}, {%s}, 0x%08Xu, bits_%s },   /* %s */' % (
            k[:2], owner[k], ','.join(str(int(x)) for x in pick), ','.join(str(int(code[x])) for x in pick),
            fnv(code[mask]), k, k))
    d.append('const ComboDir combo_dir[] = {')
    d += ents
    d.append('    { 0, 0xFF, {0}, {0}, 0, 0 } };')
    d.append('const int combo_count = %d;' % len(combos))
    dirc = '\n'.join(d) + '\n'
    os.makedirs(out, exist_ok=True)
    for i, c in enumerate(combos):
        o = os.path.join(out, 'c%02d' % i)
        if os.path.isdir(o): shutil.rmtree(o)
        os.makedirs(o)
        for f in ('huc_ops.h', 'interp.c', 'huc_rt.c'):
            shutil.copy(os.path.join(gen, f), o)
        for k in SHARED + sorted(c):
            shutil.copy(os.path.join(gen, 'blk_%s.c' % k), o)
        if SPLIT_DIRS:                                      # (the hot halves: from every window, so the shared blocks'
            own = OWN.get(i, '')                            #  cold halves are the same in every combination; its own
            os.environ['SPLIT_OWN'] = ','.join(d for d in SPLIT_DIRS if os.path.basename(d) in own.split('+'))
            sp.split(W, o, SPLIT_DIRS)                      #  windows' counts for the overlay banks: COMBO_OWN)
        for k in SHARED:                                    # (the shared blocks: bks_*, linked at 0x022A0000)
            os.rename(os.path.join(o, 'blk_%s.c' % k), os.path.join(o, 'bks_%s.c' % k))
        for name, keys, tab in (('blocks_sh.c', SHARED, 'blocks_sh'), ('blocks_cb.c', sorted(c), 'blocks_cb')):
            L = [head]
            for k in keys: L.append('void blk_%s(Cpu *c);\n' % k)
            for k in keys:
                for a in ('code', 'mask'):
                    L.append('static const uint8_t %s_%s[8192] = {%s};\n' % (a, k, ','.join(str(x) for x in arr[(a, k)].tolist())))
            L.append('const BlockDef %s[] = {\n' % tab)
            for k in keys: L.append('    { 0x%s, "%s", blk_%s, code_%s, mask_%s },\n' % (k[:2], k, k, k, k))
            L.append('    { 0, NULL, NULL, NULL, NULL } };\n')
            if tab == 'blocks_cb':
                L.append('/* the file\'s header, at its start (saspeed.ld .blkc): the runtime reads the table from here */\n')
                hot = os.path.exists(os.path.join(o, 'hot.c'))
                L.append('typedef struct { const char *key; void (*fn)(Cpu *); uint8_t id, slot; } HotDef;\n')
                if hot:
                    L.append('extern const HotDef hot_blocks[]; extern char _chot_lma[], _chot_start[], _chot_end[];   /* (the link script __chot_*: C names take a leading _) */\n')
                    L.append('extern void *const hs_subtab[] __attribute__((weak)); extern const int16_t hs_kofftab[] __attribute__((weak));\n')
                L.append('const struct { uint32_t magic, combo; const BlockDef *tab; const HotDef *hot; const char *hot_lma; char *hot_vma; '
                         'const char *hot_end; void *const *subtab; const int16_t *kofftab; } combo_head __attribute__((section(".combo_head"), used)) = '
                         '{ 0x53434232u, %du, blocks_cb, %s };\n' % (i, 'hot_blocks, _chot_lma, _chot_start, _chot_end, hs_subtab, hs_kofftab' if hot else '0, 0, 0, 0, 0, 0'))
            open(os.path.join(o, name), 'w').write(''.join(L))
        open(os.path.join(o, 'combo_dir.c'), 'w').write(dirc)
        print('c%02d: %s  %d KB' % (i, ' '.join(sorted(c)), sum(sizes[k] for k in c) >> 10))
    print('shared: %s  %d KB' % (' '.join(SHARED), sum(sizes[k] for k in SHARED) >> 10))


if __name__ == '__main__':
    main()
